const LegalDraft = require('../models/LegalDraft');
const Suspect = require('../models/Suspect');
const logger = require('../utils/logger');
const { generatePdf } = require('../utils/pdfGenerator');

exports.assistLegal = async (req, res) => {
  try {
    const { description, includeDraft } = req.body;
    // Placeholder: AI-driven legal section suggestion
    const suggestedSections = [
      { code: 'NDPS 21', description: 'Punishment for possession of manufactured drugs' },
      { code: 'NDPS 22', description: 'Punishment for sale of synthetic drugs' },
    ];

    const draft = new LegalDraft({
      description,
      suggestedSections,
      draftSummary: includeDraft ? `Draft based on: ${description}` : null,
    });
    await draft.save();

    logger.info(`Legal assist generated by ${req.officer.email}`);
    res.json({
      suggestedSections,
      draftSummary: draft.draftSummary,
    });
  } catch (error) {
    logger.error('Error generating legal assist:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

exports.generateFir = async (req, res) => {
  try {
    const { suspectId, incidentDate, location, evidence, officerName } = req.body;
    const suspect = await Suspect.findById(suspectId);
    if (!suspect) return res.status(404).json({ message: 'Suspect not found' });

    // Placeholder: Generate FIR PDF
    const firContent = { suspect, incidentDate, location, evidence, officerName };
    const firPdfUrl = await generatePdf(firContent, 'pdf', suspectId, 'fir');

    const draft = new LegalDraft({
      suspectId,
      firPdfUrl,
    });
    await draft.save();

    logger.info(`FIR generated for suspect ${suspectId} by ${req.officer.email}`);
    res.json({ firDocument: firPdfUrl, status: 'generated' });
  } catch (error) {
    logger.error('Error generating FIR:', error);
    res.status(500).json({ message: 'Server error' });
  }
};